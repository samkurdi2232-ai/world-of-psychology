// Global cached instance
export const MEGA_10K_TOPICS: Topic10k[] = generateMega10kTopics();

// Fast indexed lookups
export function getTopic10kById(id: number): Topic10k | undefined {
  if (id < 1 || id > MEGA_10K_TOPICS.length) return undefined;
  return MEGA_10K_TOPICS[id - 1];
}

export function getTopics10kByCategory(category: CategoryKey): Topic10k[] {
  return MEGA_10K_TOPICS.filter(t => t.category === category);
}

export function search10kTopics(query: string, category?: CategoryKey | "all", limit = 100): Topic10k[] {
  const q = query.toLowerCase().trim();
  const filtered = MEGA_10K_TOPICS.filter(t => {
    if (category && category !== "all" && t.category !== category) return false;
    if (!q) return true;
    return (
      t.titleKu.toLowerCase().includes(q) ||
      t.titleEn.toLowerCase().includes(q) ||
      t.shortDesc.toLowerCase().includes(q) ||
      t.symptoms.some(s => s.toLowerCase().includes(q)) ||
      t.causes.some(c => c.toLowerCase().includes(q)) ||
      t.treatment.some(tr => tr.toLowerCase().includes(q))
    );
  });
  return filtered.slice(0, limit);
}
